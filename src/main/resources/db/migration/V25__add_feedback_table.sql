-- ============================================================
-- V25__add_feedback_table.sql
-- Feedback system: bug reports, feature requests and general feedback.
--
--  * type    : one of 'bug' | 'feature' | 'general' (validated in the app layer)
--  * rating  : 1-5 stars (validated in the app layer)
--  * status  : workflow state ('new' by default). Bug/feature rows are private;
--              only type='general' rows are exposed by GET /api/feedback/public.
--  * created_at: set by the entity (@CreatedDate) and also defaulted here as a
--                safety net so a raw INSERT can never leave it NULL.
--
-- No FK to users: feedback may be submitted by anonymous visitors, and we
-- deliberately store only a denormalised first name / email (never a link)
-- so public listings can never leak account data.
-- ============================================================

CREATE TABLE feedback (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type        VARCHAR(20)  NOT NULL,
    rating      INTEGER      NOT NULL,
    title       VARCHAR(120) NOT NULL,
    details     TEXT         NOT NULL,
    user_name   VARCHAR(120),
    user_email  VARCHAR(160),
    page_url    VARCHAR(500),
    user_agent  VARCHAR(500),
    status      VARCHAR(30)  NOT NULL DEFAULT 'new',
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_feedback_type       ON feedback(type);
CREATE INDEX idx_feedback_status     ON feedback(status);
CREATE INDEX idx_feedback_created_at ON feedback(created_at DESC);
